#!/usr/bin/env bash
set -euo pipefail

binary_name="aef"
default_prefix="/usr/local/bin"
prefix="$default_prefix"
assume_yes=0

usage() {
  cat <<'EOF'
Usage: scripts/install.sh [--prefix DIR] [--yes]

Builds and installs the aef binary into DIR (default: /usr/local/bin).

The default prefix requires an explicit confirmation. There is no sudo
escalation: if you lack write permission, choose a writable --prefix such as
"$HOME/.local/bin" and add it to PATH.

Options:
  --prefix DIR   Install into DIR instead of /usr/local/bin (explicit opt-in).
  --yes          Do not prompt (use only when you have already reviewed the target).
  --help         Show this help.

A manifest is written to DIR/.aef-install-manifest listing the installed binary.
Uninstall with scripts/uninstall.sh --prefix DIR --manifest DIR/.aef-install-manifest
The manifest never contains credentials, and this script never installs
provider skills or modifies provider configuration.
EOF
}

fail() {
  printf 'install.sh: %s\n' "$1" >&2
  exit 2
}

confirm() {
  local question="$1"
  local answer=""
  if [[ ! -t 0 ]]; then
    printf 'install.sh: non-interactive shell; pass --yes to confirm: %s\n' "$question" >&2
    return 2
  fi
  printf '%s [y/N] ' "$question"
  read -r answer
  case "$answer" in
    y | Y | yes | YES) return 0 ;;
    *) return 1 ;;
  esac
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix)
      [[ $# -ge 2 ]] || fail "--prefix requires a directory"
      prefix="$2"
      shift 2
      ;;
    --prefix=*)
      prefix="${1#*=}"
      shift
      ;;
    --yes | -y)
      assume_yes=1
      shift
      ;;
    --help | -h)
      usage
      exit 0
      ;;
    *)
      fail "unknown argument: $1"
      ;;
  esac
done

[[ -n "$prefix" ]] || fail "--prefix must not be empty"

if [[ "$prefix" == "$default_prefix" && "$assume_yes" -eq 0 ]]; then
  confirm "Install $binary_name into $default_prefix?" || exit 1
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

command -v go >/dev/null 2>&1 || fail "Go toolchain not found on PATH"

target="$prefix/$binary_name"
if [[ -e "$target" && "$assume_yes" -eq 0 ]]; then
  confirm "Overwrite existing $target?" || exit 1
fi

build_dir="$(mktemp -d)"
trap 'rm -rf "$build_dir"' EXIT
go build -o "$build_dir/$binary_name" ./cmd/aef

mkdir -p "$prefix"
install -m 0755 "$build_dir/$binary_name" "$target"

manifest="$prefix/.aef-install-manifest"
{
  printf '# AEF install manifest (generated by scripts/install.sh)\n'
  printf 'binary=%s\n' "$target"
} > "$manifest"
chmod 0644 "$manifest"

printf 'Installed %s\n' "$target"
printf 'Manifest: %s\n' "$manifest"
printf 'Uninstall: scripts/uninstall.sh --prefix %s --manifest %s\n' "$prefix" "$manifest"
